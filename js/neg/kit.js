export const pitchText = (me, version) => version.blocks.map((k) => (me[k] || "").trim()).filter(Boolean).join(" ");

export function positionText(me) {
  const v = (k) => (me[k] || "").trim();
  if (!v("forWho") && !v("pain")) return "";
  return [`Для ${v("forWho") || "…"} мы ${v("pain") || "…"}`, v("unlike") && `в отличие от ${v("unlike")}`, v("proof") && `потому что ${v("proof")}`]
    .filter(Boolean).join(", ") + ".";
}
